; B is our Chamber that is loaded
; C is a loop for every turn that is decremented

PORTA1: EQU 50H
PORTB1: EQU 51H
PORTC1: EQU 52H
CTRLP1: EQU 53H

PORTA2: EQU 60H
PORTB2: EQU 61H
PORTC2: EQU 62H
CTRLP2: EQU 63H

PORTA3: EQU 70H
PORTB3: EQU 71H
PORTC3: EQU 72H
CTRLP3: EQU 73H

PORTA4: EQU 80H
PORTB4: EQU 81H
PORTC4: EQU 82H
CTRLP4: EQU 83H

PORTA5: EQU 90H
PORTB5: EQU 91H
PORTC5: EQU 92H
CTRLP5: EQU 93H


ORG 0000H
JMP START
ORG 002CH ; PRE SET ISR FOR RST5.5 INTERRUPT.
JMP ISR5_5

START:
LXI SP,3FF0H
MVI A, 00011110B ; Masked 6.5 AND 5.5, 7.5 available
SIM
EI

MVI A,10001001B
OUT CTRLP1

MVI A,10000000B
OUT CTRLP2

MVI A,10000000B
OUT CTRLP3

MVI A,10000000B
OUT CTRLP4

MVI A,10000000B
OUT CTRLP5

MVI B,00H
mvi C,06H
MVI D,00H
MVI E,0FFH
MVI A,00H

;(Clear 7 Segment)
OUT PORTB1
OUT PORTA2
OUT PORTB2
OUT PORTC2
OUT PORTA3
OUT PORTB3
OUT PORTC3
OUT PORTA4
OUT PORTB4
OUT PORTC4
OUT PORTA5
OUT PORTB5
OUT PORTC5

CHECKKYP: ; KEYPAD PORTC
	
	MVI A,00H
	OUT PORTB3
	MVI A,3FH
	OUT PORTB1
	MVI A,00H
	IN PORTC1 ; 1
	MVI B,05H
	ANI 10H
	JNZ SHOWTIME

	MVI A,00H
	OUT PORTB1
	MVI A,3FH
	OUT PORTA2
	MVI A,00H
	IN PORTC1
	MVI B,04H ; 2
	ANI 10H
	JNZ SHOWTIME

	MVI A,00H
	OUT PORTA2
	MVI A,3FH
	OUT PORTB2
	MVI A,00H
	IN PORTC1
	MVI B,01H ; 3
	ANI 10H
	JNZ SHOWTIME

	MVI A,00H
	OUT PORTB2
	MVI A,3FH
	OUT PORTC2
	MVI A,00H
	IN PORTC1
	MVI B,02H ; 4
	ANI 10H
	JNZ SHOWTIME
	
	MVI A,00H
	OUT PORTC2
	MVI A,3FH
	OUT PORTA3
	MVI A,00H
	IN PORTC1
	MVI B,06H ; 5 
	ANI 10H
	JNZ SHOWTIME
	
	MVI A,00H
	OUT PORTA3
	MVI A,3FH
	OUT PORTB3
	MVI A,00H
	IN PORTC1
	MVI B,03H ; 6
	ANI 10H
	JNZ SHOWTIME
	
	JZ CHECKKYP ; loop

WAIT_TRIGGER:	; Press any button again
		
	MVI A,00H
	IN PORTC1
	ANI 10H
	JZ WAIT_TRIGGER
	JMP OPERATION

OPERATION: 
	MOV A,B
	CMP C
	JZ LOSE; If the value are the same, bro loses. 
	CALL SHOTTED
	CALL PLAYER_SWITCH
	DCR C
	INR D
	JMP WAIT_TRIGGER

	
LOSE: 
	MVI A,38H
	OUT PORTB4
	MVI A,3FH
	OUT PORTC4
	MVI A,6DH
	OUT PORTA5
	MVI A,4FH
	OUT PORTB5
	CALL DELAY
	RST 0

SHOWTIME:
	MVI A,3FH
	OUT PORTB1
	OUT PORTA2
	OUT PORTB2
	OUT PORTC2
	OUT PORTA3
	OUT PORTB3
	MVI A,73H
	OUT PORTC3
	MVI A,06H
	OUT PORTA4
	JMP WAIT_TRIGGER

PLAYER_SWITCH:
	MOV A,E
	CPI 00H
	CZ PLAYER1
	CPI 0FFh
	CZ PLAYER2
	MOV A,E
	CMA
	MOV E,A
	RET

PLAYER1:
	MVI A,06H
	OUT PORTA4
	RET

PLAYER2:
	MVI A,5BH
	OUT PORTA4
	RET

SHOTTED:
	MOV A,D
	CPI 00H
	CZ SHOT1
	CPI 01H
	CZ SHOT2
	CPI 02H
	CZ SHOT3
	CPI 03H
	CZ SHOT4
	CPI 04H
	CZ SHOT5
	CPI 05H
	CZ SHOT6
	RET

SHOT1:
	MVI A, 40H ;(-)
	OUT PORTB1
	RET
	

SHOT2:
	MVI A, 40H ;(-)
	OUT PORTA2
	RET

SHOT3:
	MVI A, 40H ;(-)
	OUT PORTB2
	RET

SHOT4:
	MVI A, 40H ;(-)
	OUT PORTC2
	RET

SHOT5:
	MVI A, 40H ;(-)
	OUT PORTA3
	RET

SHOT6:
	MVI A, 40H ;(-)
	OUT PORTB3
	RET

DELAY:      MVI A, 2FH        ; 255 inner loops
DELAY_LOOP: DCR A
            JNZ DELAY_LOOP
            RET

ISR5_5:
	CALL PAUSE
	CALL DELAY
	CALL CLEAR_STAT
	EI
	RET
	
PAUSE:
	MVI A,73H
	OUT PORTB4
	MVI A,77H
	OUT PORTC4
	MVI A,3EH
	OUT PORTA5
	MVI A,6DH
	OUT PORTB5
	MVI A,79H
	OUT PORTC5
	RET 

CLEAR_STAT:
	MVI A,00H
	OUT PORTB4
	OUT PORTC4
	OUT PORTA5
	OUT PORTB5
	OUT PORTC5
	RET
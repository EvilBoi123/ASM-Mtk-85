PORTA: EQU 80H
PORTB: EQU 81H
PORTC: EQU 82H
CTRLP: EQU 83H
ORG 0000H
LXI SP,3FFFH
MVI A,10011001B
OUT CTRLP
MVI A,00H
MVI B,00H
MVI D,00H

CHECKKYP:
	IN PORTC
	ANI 10H
	JZ NEXT1
	MVI B, 06H
	JMP WAIT_RELEASE

NEXT1:
	IN PORTC
	ANI 10H
	JZ NEXT2
	MVI B, 05H
	JMP WAIT_RELEASE

NEXT2:
	IN PORTC
	ANI 10H
	JZ NEXT3
	MVI B, 04H
	JMP WAIT_RELEASE
NEXT3:
	IN PORTC
	ANI 10H
	JZ NEXT4
	MVI B, 03H
	JMP jump

NEXT4:
	IN PORTC
	ANI 10H
	JZ NEXT5
	MVI B, 02H
	JMP WAIT_RELEASE

NEXT5:
	IN PORTC
	ANI 10H
	JZ CHECKKYP
	MVI B, 01H
	JMP WAIT_RELEASE

	JZ CHECKKYP

	IN PORTC
	ANI 0FH
	CALL LOOK
	OUT PORTB
	JMP CHECKKYP
	HLT


LOOK: 
	LXI H,TABLE
	MOV L,A
	MOV A,M
	RET

jump:
WAIT_TRIGGER:
	IN PORTC
	ANI 01H         ; Use bit 0 as trigger
	JZ WAIT_TRIGGER ; Wait until trigger pulled

	INR D           ; next chamber
	MOV A, D
	CMP B           ; bullet in this chamber?
	JZ DEAD

	MVI A, 01H
	OUT PORTA       ; survived shot

WAIT_RELEASE:
	IN PORTC
	ANI 01H
	JNZ WAIT_RELEASE ; Wait until button released (debounce)

	JMP WAIT_TRIGGER  ; Wait for next trigger pull

; ======= DEAD BRANCH =======
DEAD:
	HLT

	;org 2000H
TABLE: DFB 06H,5BH,4FH,77H,66H,6DH,7DH,7CH,07H,7FH,6FH,39H,62H,3FH,76H,5EH


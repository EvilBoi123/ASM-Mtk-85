; B is our Chamber that is loaded
; C is a loop for every turn that is decremented

PORTA: EQU 80H
PORTB: EQU 81H
PORTC: EQU 82H
CTRLP: EQU 83H
ORG 0000H
LXI SP,3FFFH
MVI A,10011001B
OUT CTRLP
MVI B,00H
MVI A,00H
mvi C,06H




CHECKKYP: ; KEYPAD PORTC
	IN PORTC ; 1
	MVI B,01H
	ANI 10H
	JNZ WAIT_TRIGGER

	IN PORTC
	MVI B,02H ; 2
	ANI 10H
	JNZ WAIT_TRIGGER

	IN PORTC
	MVI B,03H ; 3
	ANI 10H
	JNZ WAIT_TRIGGER

	IN PORTC
	MVI B,04H ; 4
	ANI 10H
	JNZ WAIT_TRIGGER
	

	IN PORTC
	MVI B,05H ; 5 
	ANI 10H
	JNZ WAIT_TRIGGER
	
	IN PORTC
	MVI B,06H ; 6
	ANI 10H
	JNZ WAIT_TRIGGER
	
	JZ CHECKKYP ; loop

WAIT_TRIGGER:	; Press any button again
		IN PORTC
		ANI 10H
		JZ WAIT_TRIGGER
		JMP OPERATION

OPERATION: 
	MOV A,B
	CMP C
	JZ LOSE; If the value are the same, bro loses. 
	DCR C
	JMP WAIT_TRIGGER
	
LOSE: 
	HLT


